"""Regenerate idle.js and idle/ from the live Idle Game (https://github.com/sgilson7/idle-game).

Usage: python3 -I tools/build_idle.py
Names come from the published data/strings.json and pictures from its icons.svg: the live
build is ahead of the repository's main branch. icons.svg is copied here, trimmed to what the
page uses, with the game's MIT license beside it. Anything without an icon is left out.
"""
import json, os, re, urllib.request

SITE = "https://sgilson7.github.io/idle-game/"
LICENSE = "https://raw.githubusercontent.com/sgilson7/idle-game/main/LICENSE"

# The game's sidebar sections, and which of its tabs count as a skill for a reading.
SKILLS = {
    "Gather": ["woodcutting", "mining", "fishing", "farming", "husbandry"],
    "Make": ["firemaking", "fletching", "smithing", "cooking", "crafting", "runecrafting", "construction", "chemistry"],
    "Fight": ["combat", "weapons", "armour", "jewellery", "lore"],
    "Engines": ["performance", "stage", "trader", "estate", "exploration", "workshop", "observatory", "cult",
                "computerization"],
}


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (ptonklescopes data build)"})
    return urllib.request.urlopen(req, timeout=30).read()


strings = json.loads(get(SITE + "data/strings.json"))
sheet = get(SITE + "icons.svg").decode()
symbols = {m.group(1): m.group(0) for m in re.finditer(r'<symbol id="([^"]+)".*?</symbol>', sheet, re.S)}


def skill_name(key):
    return strings["skills"].get(key, {}).get("name") or strings["ui"][f"tab_{key}"]


skills = [{"key": k, "name": skill_name(k), "group": group, "icon": k}
          for group, keys in SKILLS.items() for k in keys if k in symbols]
items = [{"name": name, "icon": k} for k, name in strings["items"].items() if k in symbols]
enemies = [{"name": name, "icon": k} for k, name in strings["enemies"].items() if k in symbols]
actions = sorted(set(strings["actions"].values()))
used = sorted({"tree"} | {t["icon"] for t in skills + items + enemies})
missing = [k for keys in SKILLS.values() for k in keys if k not in symbols]

os.makedirs("idle", exist_ok=True)
open("idle/LICENSE", "wb").write(get(LICENSE))
open("idle/icons.svg", "w").write(
    '<svg xmlns="http://www.w3.org/2000/svg">\n' + "\n".join(symbols[k] for k in used) + "\n</svg>\n")
open("idle.js", "w").write(
    "// Generated by tools/build_idle.py. Do not edit by hand.\n"
    f"export const IDLE_SKILLS = {json.dumps(skills, indent=1)};\n"
    f"export const IDLE_ITEMS = {json.dumps(items, indent=1)};\n"
    f"export const IDLE_ENEMIES = {json.dumps(enemies, indent=1)};\n"
    f"export const IDLE_ACTIONS = {json.dumps(actions, indent=1)};\n")
print(len(skills), "skills,", len(items), "items,", len(enemies), "enemies,", len(actions), "actions; no icon for:", missing)
