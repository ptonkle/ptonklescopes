"""Regenerate data.js from Data Dragon (champions) and CommunityDragon (TFT set).

Usage: python3 -I tools/build_data.py path/to/cdragon-tft-en_us.json
"""
import json, sys, urllib.request

CD = "https://raw.communitydragon.org/latest/game/"
# Optional second argument pins a set number; by default the newest set is used.

# Set names aren't in the game data; add the new one here when a set launches.
SET_NAMES = {18: "Enchanted Wilds"}

def tex(path):
    return CD + path.lower().replace(".tex", ".png")

versions = json.load(urllib.request.urlopen("https://ddragon.leagueoflegends.com/api/versions.json"))
champs = json.load(urllib.request.urlopen(
    f"https://ddragon.leagueoflegends.com/cdn/{versions[0]}/data/en_US/champion.json"))["data"]
runes = json.load(urllib.request.urlopen(
    f"https://ddragon.leagueoflegends.com/cdn/{versions[0]}/data/en_US/runesReforged.json"))
keystones = [{"key": r["key"], "name": r["name"], "icon": "https://ddragon.leagueoflegends.com/cdn/img/" + r["icon"]}
             for tree in runes for r in tree["slots"][0]["runes"]]
lol = [{"id": c["id"], "name": c["name"], "title": c["title"], "tags": c["tags"]}
       for c in sorted(champs.values(), key=lambda c: c["name"])]

tft = json.load(open(sys.argv[1]))
number = int(sys.argv[2]) if len(sys.argv) > 2 else max(x["number"] for x in tft["setData"])
s = next(x for x in tft["setData"] if x["mutator"] == f"TFTSet{number}")
units = [u for u in s["champions"] if u.get("traits") and not u["name"].startswith("Lux (")]
traits = []
for t in s["traits"]:
    members = sorted((u for u in units if t["name"] in u["traits"]), key=lambda u: -u["cost"])
    def art(u):
        p = u["icon"] if u["icon"].startswith("assets/") else u["squareIcon"]
        return tex(p)
    traits.append({
        "name": t["name"],
        "icon": tex(t["icon"]),
        "units": [{"name": u["name"], "cost": u["cost"], "art": art(u), "tile": tex(u["tileIcon"])}
                  for u in members],
    })
traits.sort(key=lambda t: t["name"])

out = ("// Generated by tools/build_data.py. Do not edit by hand.\n"
       f"export const DDRAGON = {json.dumps(versions[0])};\n"
       f"export const TFT_SET = {{ number: {number}, name: {json.dumps(SET_NAMES.get(number, ''))} }};\n"
       f"export const KEYSTONES = {json.dumps(keystones, indent=1)};\n"
       f"export const CHAMPIONS = {json.dumps(lol, separators=(',', ':'))};\n"
       f"export const TRAITS = {json.dumps(traits, indent=1)};\n")
open("data.js", "w").write(out)
print(len(lol), "champions,", len(traits), "traits")
