"""Regenerate factorio.js from Wube's factorio-data (base + Space Age).

Usage: python3 -I tools/build_factorio.py
Items and technologies come from the Lua prototypes; icons are the official wiki's,
and anything without a wiki icon is left out.
"""
import json, re, urllib.error, urllib.parse, urllib.request
from concurrent.futures import ThreadPoolExecutor

RAW = "https://raw.githubusercontent.com/wube/factorio-data/master/"
WIKI = "https://wiki.factorio.com/images/"

# Reading category for each item subgroup; subgroups not listed are left out.
CATEGORY = {
    **dict.fromkeys(["belt", "inserter", "storage", "transport", "train-transport", "logistic-network",
                     "energy-pipe-distribution", "circuit-network", "terrain", "tool"], "logistics"),
    **dict.fromkeys(["production-machine", "smelting-machine", "extraction-machine", "energy", "module",
                     "agriculture", "environmental-protection"], "production"),
    **dict.fromkeys(["raw-material", "raw-resource", "intermediate-product", "science-pack", "uranium-processing",
                     "agriculture-products", "agriculture-processes", "nauvis-agriculture", "vulcanus-processes",
                     "fulgora-processes", "aquilo-processes"], "intermediate"),
    **dict.fromkeys(["gun", "turret", "defensive-structure", "military-equipment", "equipment",
                     "utility-equipment"], "combat"),
    **dict.fromkeys(["space-related", "space-platform", "space-material", "space-interactors", "space-rocket"], "space"),
}
# Items whose prototype has no subgroup: categorise by type.
TYPE_CATEGORY = {"ammo": "combat", "gun": "combat", "armor": "combat", "capsule": "combat"}
SKIP_TYPES = {"blueprint", "blueprint-book", "copy-paste-tool", "upgrade-item", "deconstruction-item",
              "spidertron-remote"}
UPPER = {"mk2": "MK2", "mk3": "MK3"}


def fetch(path):
    return urllib.request.urlopen(RAW + path).read().decode()


def entries(src, kinds):
    pat = r'type\s*=\s*"(%s)"\s*,\s*name\s*=\s*"([a-z0-9-]+)"(.*?)(?=\n\s*\{\s*\n\s*type\s*=|\Z)' % "|".join(kinds)
    for m in re.finditer(pat, src, re.S):
        yield m.groups()


def display(name):
    words = [UPPER.get(w, w) for w in name.split("-")]
    text = " ".join(words)
    return text[0].upper() + text[1:]


def has_icon(file):
    try:
        req = urllib.request.Request(WIKI + urllib.parse.quote(file), method="HEAD",
                                     headers={"User-Agent": "Mozilla/5.0 (ptonklescopes data build)"})
        return urllib.request.urlopen(req, timeout=20).status == 200
    except urllib.error.URLError:
        return False


item_kinds = ["item", "ammo", "gun", "capsule", "module", "item-with-entity-data", "armor", "repair-tool",
              "rail-planner", "space-platform-starter-pack", "tool"] + sorted(SKIP_TYPES)
items = []
for dlc, path in ((False, "base/prototypes/item.lua"), (True, "space-age/prototypes/item.lua")):
    for kind, name, body in entries(fetch(path), item_kinds):
        if kind in SKIP_TYPES or "hidden = true" in body:
            continue
        sg = re.search(r'subgroup\s*=\s*"([a-z0-9-]+)"', body)
        cat = CATEGORY.get(sg.group(1)) if sg else TYPE_CATEGORY.get(kind)
        if name == "space-platform-foundation":
            cat = "space"
        if cat:
            items.append({"name": display(name), "category": cat, "spaceAge": dlc})

techs = []
for dlc, path in ((False, "base/prototypes/technology.lua"), (True, "space-age/prototypes/technology.lua")):
    for _, name, body in entries(fetch(path), ["technology"]):
        if "hidden = true" in body:
            continue
        techs.append({"name": display(name), "spaceAge": dlc})

# Keep the first definition of each name (Space Age re-declares some base prototypes).
items = list({i["name"]: i for i in reversed(items)}.values())[::-1]
techs = list({t["name"]: t for t in reversed(techs)}.values())[::-1]

def item_icon(item):
    file = item["name"].replace(" ", "_") + ".png"
    return WIKI + file if has_icon(file) else None


def tech_icon(tech):
    # Levelled research ("Mining productivity 3") shares the unnumbered icon.
    for name in (tech["name"], re.sub(r" \d+$", "", tech["name"])):
        file = name.replace(" ", "_") + "_(research).png"
        if has_icon(file):
            return WIKI + file
    return None


with ThreadPoolExecutor(16) as pool:
    item_icons = list(pool.map(item_icon, items))
    tech_icons = list(pool.map(tech_icon, techs))
dropped = [i["name"] for i, u in zip(items + techs, item_icons + tech_icons) if not u]
items = [dict(i, icon=u) for i, u in zip(items, item_icons) if u]
techs = [dict(t, icon=u) for t, u in zip(techs, tech_icons) if u]

open("factorio.js", "w").write(
    "// Generated by tools/build_factorio.py. Do not edit by hand.\n"
    f"export const FACTORIO_ITEMS = {json.dumps(items, indent=1)};\n"
    f"export const FACTORIO_TECHS = {json.dumps(techs, indent=1)};\n")
print(len(items), "items,", len(techs), "technologies; no wiki icon for:", dropped)
